// Suit les dimensions du grand panneau, y compris sur mobile.
function resizePortalDNA() {
  if (!panel) return;
  const svg = panel.querySelector(".d8-portal-dna");
  if (!svg) return;
  const width = panel.clientWidth;
  const height = panel.clientHeight;
  if (!width || !height) return;
  svg.setAttribute("viewBox", `0 0 ${width} ${height}`);
  svg.querySelectorAll("rect").forEach(rect => {
    rect.setAttribute("x", "4");
    rect.setAttribute("y", "4");
    rect.setAttribute("width", String(Math.max(0, width - 8)));
    rect.setAttribute("height", String(Math.max(0, height - 8)));
    rect.setAttribute("rx", "20");
    rect.setAttribute("pathLength", "1000");
  });
}

if (panel && typeof ResizeObserver !== "undefined") {
  new ResizeObserver(resizePortalDNA).observe(panel);
}

